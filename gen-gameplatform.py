#!/usr/bin/env python3
"""Emit the class and slot table of Wine's winegameplatform (dlls/winegameplatform/slots.h) from
Microsoft.GamePlatform.Services.winmd.

Every runtime class of the Gaming Services client with an I<Class>Statics interface gets a traced stand-in
factory: one entry per slot with the method's name, and whether it is an event add_/remove_. The module answers
the slots it implements and traces the rest (it returns what the package's own client returns without the
service, 0x87E00196), so one run names every call the app makes.

  gen-gameplatform.py <Microsoft.GamePlatform.Services.winmd> <out.h>
"""
import os, re, subprocess, sys

winmd, out = sys.argv[1:3]
# instance interfaces whose objects the module hands out with the same traced slots (gp_classes entries "<Name>Instance")
INSTANCES = ["IPackage"]
here = os.path.dirname(os.path.abspath(__file__))
def run(*a):
    return subprocess.run([sys.executable, os.path.join(here, "winmd.py"), winmd] + list(a),
                          capture_output=True, text=True).stdout

types = [l.split() for l in run("--grep", "").splitlines() if l and not l[0].isspace()]
ns = "Microsoft.GamePlatform.Services."
classes = []
for t in types:
    if len(t) < 2 or not t[0].startswith(ns) or "." in t[0][len(ns):]: continue
    iface = t[0][len(ns):]
    m = re.fullmatch(r"I(\w+)Statics", iface)
    if m: cls = m.group(1)
    elif iface in INSTANCES: cls = iface[1:] + "Instance"   # an object the module hands out, traced the same way
    else: continue
    iid = t[1]
    slots = []
    for l in run("--sig", t[0]).splitlines():
        s = re.match(r"\s+slot\s+(\d+)\s+(.*?)\s(\w+)\((.*)\)$", l)
        if s: slots.append((int(s.group(1)), s.group(3), s.group(2), s.group(4)))
    classes.append((cls, iid, slots))

def guid(g):
    p = g.split("-")
    b = p[3] + p[4]
    return "{0x%s,0x%s,0x%s,{%s}}" % (p[0], p[1], p[2], ",".join("0x" + b[i:i+2] for i in range(0, 16, 2)))

with open(out, "w") as f:
    f.write("/* generated by gen-gameplatform.py from Microsoft.GamePlatform.Services.winmd: do not edit */\n")
    for cls, iid, slots in classes:
        f.write("static const struct gp_slot gp_slots_%s[] = {\n" % cls)
        for n, name, ret, args in slots:
            kind = 1 if name.startswith("add_") else 2 if name.startswith("remove_") else 0
            f.write('    { %d, "%s", %d }, /* %s(%s) */\n' % (n, name, kind, ret.replace("*/", ""), args.replace("*/", "")))
        f.write("};\n")
    f.write("static const struct gp_class gp_classes[] = {\n")
    for cls, iid, slots in classes:
        f.write('    { L"%s%s", %s, ARRAY_SIZE(gp_slots_%s), gp_slots_%s },\n' % (ns, cls, guid(iid), cls, cls))
    f.write("};\n")
print("%d classes" % len(classes))
